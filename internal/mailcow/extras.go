// Mailbox extras (spam score, app passwords, disposable aliases), alias domains, domain
// footers, DKIM selectors and zero-downtime rotation, quarantine previews and sender
// allow/block lists.

var (
	reSelector   = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,62}$`)
	rePolicyFrom = regexp.MustCompile(`^[a-z0-9@_.*-]{1,255}$`)
	appProtocols = map[string]bool{"imap": true, "smtp": true, "eas": true, "dav": true, "pop3": true, "sieve": true}
)

// dkimRotation is a key generated by CowSec that waits for its DNS record before mailcow
// starts signing with it. The private key lives only in memory and is only ever sent to
// mailcow.
type dkimRotation struct {
	Selector string    `json:"selector"`
	KeySize  int       `json:"key_size"`
	Name     string    `json:"name"`
	Value    string    `json:"value"`
	Created  time.Time `json:"created"`
	pem      string
}

var (
	rotationsMu sync.Mutex
	rotations   = map[string]*dkimRotation{}
)

func mountExtras(r chi.Router, c *Client, o Options) {
	change := func(w http.ResponseWriter, path string, body interface{}) {
		msgs, err := c.Change(path, body)
		if err != nil {
			fail(w, http.StatusBadRequest, err)
			return
		}
		writeJSON(w, 200, map[string]interface{}{"status": "ok", "messages": msgs})
	}
	list := func(w http.ResponseWriter, path string) {
		data, err := c.List(path)
		if err != nil {
			fail(w, http.StatusBadGateway, err)
			return
		}
		writeRaw(w, data)
	}
	mailbox := func(w http.ResponseWriter, req *http.Request) (string, bool) {
		u := strings.ToLower(param(req, "username"))
		if !reEmail.MatchString(u) {
			fail(w, 400, fmt.Errorf("invalid mailbox"))
			return "", false
		}
		return u, true
	}

	// ---- spam score: junk folder above the first value, rejected above the second
	r.Get("/mailboxes/{username}/spam-score", func(w http.ResponseWriter, req *http.Request) {
		if u, ok := mailbox(w, req); ok {
			data, err := c.Get("get/spam-score/" + u)
			if err != nil {
				fail(w, http.StatusBadGateway, err)
				return
			}
			writeRaw(w, data)
		}
	})
	r.Put("/mailboxes/{username}/spam-score", func(w http.ResponseWriter, req *http.Request) {
		u, ok := mailbox(w, req)
		if !ok {
			return
		}
		var in struct {
			Default bool    `json:"default"`
			Junk    float64 `json:"junk"`
			Reject  float64 `json:"reject"`
		}
		if decode(req, &in) != nil {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		score := "default"
		if !in.Default {
			if in.Junk < 1 || in.Junk > 50 || in.Reject < in.Junk || in.Reject > 50 {
				fail(w, 400, fmt.Errorf("scores run from 1 to 50, and the reject score can't be below the junk score"))
				return
			}
			score = strconv.FormatFloat(in.Junk, 'f', -1, 64) + "," + strconv.FormatFloat(in.Reject, 'f', -1, 64)
		}
		change(w, "edit/spam-score", map[string]interface{}{"items": []string{u}, "attr": map[string]string{"spam_score": score}})
	})

	// ---- app passwords: CowSec generates them and shows them once
	r.Get("/mailboxes/{username}/app-passwords", func(w http.ResponseWriter, req *http.Request) {
		u, ok := mailbox(w, req)
		if !ok {
			return
		}
		data, err := c.List("get/app-passwd/all/" + u)
		if err != nil {
			fail(w, http.StatusBadGateway, err)
			return
		}
		// mailcow returns each row whole, password hash included; it never leaves CowSec
		var rows []map[string]interface{}
		if err := json.Unmarshal(data, &rows); err != nil {
			fail(w, http.StatusBadGateway, fmt.Errorf("unexpected app password list"))
			return
		}
		for _, row := range rows {
			delete(row, "password")
		}
		writeJSON(w, 200, rows)
	})
	r.Post("/mailboxes/{username}/app-passwords", func(w http.ResponseWriter, req *http.Request) {
		u, ok := mailbox(w, req)
		if !ok {
			return
		}
		var in struct {
			Name      string   `json:"name"`
			Protocols []string `json:"protocols"`
		}
		if decode(req, &in) != nil || strings.TrimSpace(in.Name) == "" {
			fail(w, 400, fmt.Errorf("give the app password a name"))
			return
		}
		protos := []string{}
		for _, p := range in.Protocols {
			if !appProtocols[p] {
				fail(w, 400, fmt.Errorf("unknown protocol %q", p))
				return
			}
			protos = append(protos, p+"_access")
		}
		if len(protos) == 0 {
			fail(w, 400, fmt.Errorf("allow at least one protocol"))
			return
		}
		pw, err := appPassword()
		if err != nil {
			fail(w, 500, err)
			return
		}
		msgs, err := c.Change("add/app-passwd", map[string]interface{}{"username": u, "app_name": trim(in.Name, 64),
			"app_passwd": pw, "app_passwd2": pw, "active": "1", "protocols": protos})
		if err != nil {
			fail(w, 400, err)
			return
		}
		writeJSON(w, 200, map[string]interface{}{"status": "ok", "messages": msgs, "password": pw})
	})
	// mailcow's edit needs the mailbox too: without it, it uses the API key's own name
	r.Patch("/mailboxes/{username}/app-passwords/{id}", func(w http.ResponseWriter, req *http.Request) {
		u, ok := mailbox(w, req)
		if !ok {
			return
		}
		id := chi.URLParam(req, "id")
		var in struct {
			Active bool `json:"active"`
		}
		if _, err := strconv.Atoi(id); err != nil || decode(req, &in) != nil {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		change(w, "edit/app-passwd", map[string]interface{}{"items": []string{id}, "attr": map[string]interface{}{"active": flag(in.Active), "username": u}})
	})
	r.Delete("/app-passwords/{id}", deleteByID(change, "delete/app-passwd"))

	// ---- disposable (time-limited) aliases
	r.Get("/mailboxes/{username}/spam-aliases", func(w http.ResponseWriter, req *http.Request) {
		if u, ok := mailbox(w, req); ok {
			list(w, "get/time_limited_aliases/"+u)
		}
	})
	r.Post("/mailboxes/{username}/spam-aliases", func(w http.ResponseWriter, req *http.Request) {
		u, ok := mailbox(w, req)
		if !ok {
			return
		}
		var in struct {
			Domain      string `json:"domain"`
			Description string `json:"description"`
			Hours       int    `json:"hours"`
			Permanent   bool   `json:"permanent"`
		}
		if decode(req, &in) != nil || !reDomain.MatchString(in.Domain) {
			fail(w, 400, fmt.Errorf("choose the domain for the alias"))
			return
		}
		body := map[string]interface{}{"username": u, "domain": strings.ToLower(in.Domain), "description": trim(in.Description, 255)}
		if in.Permanent {
			body["permanent"] = "1"
		} else {
			if in.Hours < 1 || in.Hours > 87600 {
				fail(w, 400, fmt.Errorf("an alias lasts between 1 hour and 10 years"))
				return
			}
			body["validity"] = strconv.Itoa(in.Hours)
		}
		change(w, "add/time_limited_alias", body)
	})
	r.Patch("/spam-aliases/{address}", func(w http.ResponseWriter, req *http.Request) {
		a := strings.ToLower(param(req, "address"))
		var in struct {
			Hours     int  `json:"hours"`
			Permanent bool `json:"permanent"`
		}
		if !reEmail.MatchString(a) || decode(req, &in) != nil || (!in.Permanent && (in.Hours < 1 || in.Hours > 87600)) {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		attr := map[string]interface{}{"validity": strconv.Itoa(in.Hours)}
		if in.Permanent {
			attr = map[string]interface{}{"permanent": "1"}
		}
		change(w, "edit/time_limited_alias", map[string]interface{}{"items": []string{a}, "attr": attr})
	})
	r.Delete("/spam-aliases/{address}", func(w http.ResponseWriter, req *http.Request) {
		a := strings.ToLower(param(req, "address"))
		if !reEmail.MatchString(a) {
			fail(w, 400, fmt.Errorf("invalid alias"))
			return
		}
		change(w, "delete/time_limited_alias", []string{a})
	})

	// ---- alias domains: every address at the alias domain reaches the same mailbox at the target
	r.Get("/alias-domains", func(w http.ResponseWriter, _ *http.Request) { list(w, "get/alias-domain/all") })
	r.Post("/alias-domains", func(w http.ResponseWriter, req *http.Request) {
		var in struct {
			AliasDomain  string `json:"alias_domain"`
			TargetDomain string `json:"target_domain"`
			Active       bool   `json:"active"`
		}
		if decode(req, &in) != nil || !reDomain.MatchString(in.AliasDomain) || !reDomain.MatchString(in.TargetDomain) {
			fail(w, 400, fmt.Errorf("enter the alias domain and the domain it points to"))
			return
		}
		change(w, "add/alias-domain", map[string]interface{}{"alias_domain": strings.ToLower(in.AliasDomain),
			"target_domain": strings.ToLower(in.TargetDomain), "active": flag(in.Active)})
	})
	r.Patch("/alias-domains/{domain}", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		var in struct {
			TargetDomain *string `json:"target_domain"`
			Active       *bool   `json:"active"`
		}
		if !reDomain.MatchString(d) || decode(req, &in) != nil {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		attr := map[string]interface{}{}
		if in.TargetDomain != nil {
			if !reDomain.MatchString(*in.TargetDomain) {
				fail(w, 400, fmt.Errorf("invalid target domain"))
				return
			}
			attr["target_domain"] = strings.ToLower(*in.TargetDomain)
		}
		if in.Active != nil {
			attr["active"] = flag(*in.Active)
		}
		change(w, "edit/alias-domain", map[string]interface{}{"items": []string{d}, "attr": attr})
	})
	r.Delete("/alias-domains/{domain}", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		if !reDomain.MatchString(d) {
			fail(w, 400, fmt.Errorf("invalid domain"))
			return
		}
		change(w, "delete/alias-domain", []string{d})
	})

	// ---- domain-wide footer (the API can set it but not read it, so reads go through the helper)
	r.Get("/domains/{domain}/footer", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		if !reDomain.MatchString(d) {
			fail(w, 400, fmt.Errorf("invalid domain"))
			return
		}
		if o.Gate == nil {
			fail(w, 503, fmt.Errorf("host helper not available"))
			return
		}
		out, err := o.Gate("mailcow-footer", d)
		if err != nil {
			fail(w, http.StatusBadGateway, err)
			return
		}
		writeRaw(w, out)
	})
	r.Put("/domains/{domain}/footer", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		var in struct {
			HTML        string   `json:"html"`
			Plain       string   `json:"plain"`
			SkipReplies bool     `json:"skip_replies"`
			Exclude     []string `json:"exclude"`
		}
		if !reDomain.MatchString(d) || decode(req, &in) != nil {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		if len(in.HTML) > 20000 || len(in.Plain) > 20000 {
			fail(w, 400, fmt.Errorf("a footer can be at most 20,000 characters"))
			return
		}
		ex := []string{}
		for _, e := range in.Exclude {
			e = strings.ToLower(strings.TrimSpace(e))
			if e == "" {
				continue
			}
			if !reEmail.MatchString(e) && !reDomain.MatchString(e) {
				fail(w, 400, fmt.Errorf("%q is not an address or alias domain", e))
				return
			}
			ex = append(ex, e)
		}
		change(w, "edit/domain/footer", map[string]interface{}{"items": []string{d}, "attr": map[string]interface{}{
			"html": in.HTML, "plain": in.Plain, "skip_replies": flag(in.SkipReplies), "exclude": ex}})
	})

	// ---- DKIM: remove, copy to other domains, rotate without a gap in signing
	r.Delete("/dkim/{domain}", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		if !reDomain.MatchString(d) {
			fail(w, 400, fmt.Errorf("invalid domain"))
			return
		}
		change(w, "delete/dkim", []string{d})
	})
	r.Post("/dkim/duplicate", func(w http.ResponseWriter, req *http.Request) {
		var in struct {
			From string   `json:"from"`
			To   []string `json:"to"`
		}
		if decode(req, &in) != nil || !reDomain.MatchString(in.From) || len(in.To) == 0 {
			fail(w, 400, fmt.Errorf("choose the domain to copy from and at least one domain to copy to"))
			return
		}
		if err := domains(in.To); err != nil {
			fail(w, 400, err)
			return
		}
		change(w, "add/dkim_duplicate", map[string]interface{}{"from_domain": in.From, "to_domain": in.To})
	})
	r.Get("/dkim/{domain}/rotation", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		rotationsMu.Lock()
		p := rotations[d]
		rotationsMu.Unlock()
		if p == nil {
			writeJSON(w, 200, map[string]interface{}{"pending": false})
			return
		}
		cur, live := dkimPublished(p.Name, p.Value)
		writeJSON(w, 200, map[string]interface{}{"pending": true, "rotation": p, "published": live, "current": cur})
	})
	r.Post("/dkim/{domain}/rotation", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		var in struct {
			Selector string `json:"selector"`
			KeySize  int    `json:"key_size"`
		}
		if !reDomain.MatchString(d) || decode(req, &in) != nil || !reSelector.MatchString(in.Selector) ||
			(in.KeySize != 2048 && in.KeySize != 3072 && in.KeySize != 4096) {
			fail(w, 400, fmt.Errorf("choose a selector (lower-case letters, digits, - and _) and a key size of 2048, 3072 or 4096"))
			return
		}
		var cur struct {
			Selector string `json:"dkim_selector"`
		}
		if data, err := c.Get("get/dkim/" + d); err == nil {
			json.Unmarshal(data, &cur)
		}
		if cur.Selector == in.Selector {
			fail(w, 400, fmt.Errorf("the new key needs a different selector from the current one (%s), so both can be published at once", cur.Selector))
			return
		}
		key, err := rsa.GenerateKey(rand.Reader, in.KeySize)
		if err != nil {
			fail(w, 500, err)
			return
		}
		pub, _ := x509.MarshalPKIXPublicKey(&key.PublicKey)
		p := &dkimRotation{Selector: in.Selector, KeySize: in.KeySize, Name: in.Selector + "._domainkey." + d,
			Value: "v=DKIM1;k=rsa;t=s;s=email;p=" + base64.StdEncoding.EncodeToString(pub), Created: time.Now().UTC(),
			pem: string(pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(key)}))}
		rotationsMu.Lock()
		rotations[d] = p
		rotationsMu.Unlock()
		writeJSON(w, 200, map[string]interface{}{"pending": true, "rotation": p, "published": false})
	})
	r.Post("/dkim/{domain}/rotation/finish", func(w http.ResponseWriter, req *http.Request) {
		d := strings.ToLower(param(req, "domain"))
		var in struct {
			Force bool `json:"force"`
		}
		decode(req, &in)
		rotationsMu.Lock()
		p := rotations[d]
		rotationsMu.Unlock()
		if p == nil {
			fail(w, 404, fmt.Errorf("no key rotation in progress for %s", d))
			return
		}
		if _, live := dkimPublished(p.Name, p.Value); !live && !in.Force {
			fail(w, 409, fmt.Errorf("DNS doesn't show the new record at %s yet", p.Name))
			return
		}
		msgs, err := c.Change("add/dkim_import", map[string]interface{}{"domain": d, "dkim_selector": p.Selector,
			"private_key_file": p.pem, "overwrite_existing": "1"})
		if err != nil {
			fail(w, 400, err)
			return
		}
		rotationsMu.Lock()
		delete(rotations, d)
		rotationsMu.Unlock()
		writeJSON(w, 200, map[string]interface{}{"status": "ok", "messages": msgs})
	})
	r.Delete("/dkim/{domain}/rotation", func(w http.ResponseWriter, req *http.Request) {
		rotationsMu.Lock()
		delete(rotations, strings.ToLower(param(req, "domain")))
		rotationsMu.Unlock()
		writeJSON(w, 200, map[string]string{"status": "ok"})
	})

	// ---- quarantine preview: headers, verdict and plain text; the HTML part is never sent to the browser
	r.Get("/quarantine/{id}", func(w http.ResponseWriter, req *http.Request) {
		id := param(req, "id")
		if _, err := strconv.Atoi(id); err != nil {
			fail(w, 400, fmt.Errorf("invalid item"))
			return
		}
		data, err := c.Get("get/quarantine/" + id)
		if err != nil {
			fail(w, http.StatusBadGateway, err)
			return
		}
		var row map[string]interface{}
		if json.Unmarshal(data, &row) != nil || row == nil {
			fail(w, 404, fmt.Errorf("quarantine item not found"))
			return
		}
		raw, _ := row["msg"].(string)
		delete(row, "msg")
		row["preview"] = previewMessage(raw)
		if s, ok := row["symbols"].(string); ok {
			var sym interface{}
			if json.Unmarshal([]byte(s), &sym) == nil {
				row["symbols"] = sym
			}
		}
		writeJSON(w, 200, row)
	})

	// ---- sender allow/block lists for a mailbox or a whole domain
	r.Get("/policies", func(w http.ResponseWriter, req *http.Request) {
		scope, target, ok := policyTarget(req.URL.Query().Get("scope"), req.URL.Query().Get("target"))
		if !ok {
			fail(w, 400, fmt.Errorf("choose a mailbox or domain"))
			return
		}
		out := map[string]json.RawMessage{}
		for _, l := range []string{"wl", "bl"} {
			data, err := c.List("get/policy_" + l + "_" + scope + "/" + target)
			if err != nil {
				fail(w, http.StatusBadGateway, err)
				return
			}
			out[l] = data
		}
		writeJSON(w, 200, out)
	})
	r.Post("/policies", func(w http.ResponseWriter, req *http.Request) {
		var in struct {
			Scope  string `json:"scope"`
			Target string `json:"target"`
			From   string `json:"from"`
			List   string `json:"list"`
		}
		if decode(req, &in) != nil {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		scope, target, ok := policyTarget(in.Scope, in.Target)
		from := strings.ToLower(strings.TrimSpace(in.From))
		if !ok || !rePolicyFrom.MatchString(from) || (in.List != "wl" && in.List != "bl") {
			fail(w, 400, fmt.Errorf("enter a sender address, domain or pattern such as *@example.org"))
			return
		}
		key := map[string]string{"mailbox": "username", "domain": "domain"}[scope]
		change(w, "add/"+scope+"-policy", map[string]interface{}{key: target, "object_from": from, "object_list": in.List})
	})
	r.Delete("/policies/{scope}/{prefid}", func(w http.ResponseWriter, req *http.Request) {
		scope, id := chi.URLParam(req, "scope"), param(req, "prefid")
		if _, err := strconv.Atoi(id); err != nil || (scope != "mailbox" && scope != "domain") {
			fail(w, 400, fmt.Errorf("invalid request"))
			return
		}
		change(w, "delete/"+scope+"-policy", []string{id})
	})

	// ---- empty the whole mail queue
	r.Post("/queue/purge", func(w http.ResponseWriter, _ *http.Request) {
		change(w, "edit/mailq", map[string]string{"action": "super_delete"})
	})
}

func policyTarget(scope, target string) (string, string, bool) {
	target = strings.ToLower(strings.TrimSpace(target))
	switch scope {
	case "mailbox":
		return scope, target, reEmail.MatchString(target)
	case "domain":
		return scope, target, reDomain.MatchString(target)
	}
	return "", "", false
}

// dkimPublished reports what DNS answers for a DKIM record and whether it carries the key.
func dkimPublished(name, value string) ([]string, bool) {
	txt, _ := net.LookupTXT(name)
	want := dkimP(value)
	for _, t := range txt {
		if want != "" && dkimP(t) == want {
			return txt, true
		}
	}
	return txt, false
}

func dkimP(record string) string {
	for _, part := range strings.Split(strings.Join(strings.Fields(record), ""), ";") {
		if strings.HasPrefix(part, "p=") {
			return part[2:]
		}
	}
	return ""
}

// appPassword returns four groups of six letters and digits (with at least one upper-case
// letter, lower-case letter and digit), separated by dashes: easy to type, and it
// satisfies any mailcow password policy.
func appPassword() (string, error) {
	const alpha = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
	for {
		b := make([]byte, 0, 27)
		for i := 0; i < 24; i++ {
			if i > 0 && i%6 == 0 {
				b = append(b, '-')
			}
			n, err := rand.Int(rand.Reader, big.NewInt(int64(len(alpha))))
			if err != nil {
				return "", err
			}
			b = append(b, alpha[n.Int64()])
		}
		s := string(b)
		if strings.ContainsAny(s, "abcdefghjkmnpqrstuvwxyz") && strings.ContainsAny(s, "ABCDEFGHJKLMNPQRSTUVWXYZ") && strings.ContainsAny(s, "23456789") {
			return s, nil
		}
	}
}
